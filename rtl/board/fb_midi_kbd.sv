// A Keyboardmania MIDI keyboard as MAME's konami/midikbd.cpp: every 10 ms the 24 keys are compared
// with the last scan; each change queues Note Off (80 nn 7F) or Note On (90 nn 7F), notes 3C-53
// from key 0, and a scan with no change queues Active Sense (FE). Bytes go out on txd at 31250
// baud, 8N1, from a 16-byte ring that is written after its index advances and read before:
// midikbd.cpp's push_tx and tra_complete, which send each byte one push late
// (docs/MAME_KLUDGES.md).

module fb_midi_kbd (
    input  logic        clk,
    input  logic        reset,
    input  logic        hold,           // the state dump: time stops
    input  logic [23:0] keys,           // 1 = down
    output logic        txd,
    input  logic [5:0]  st_a,           // [Firebeat] the state dump's register block (end of file)
    output logic [31:0] st_d,
    input  logic        st_we,
    input  logic [31:0] st_wd
);

// 10 ms and 1/31250 s from 66.667 MHz, exact: 3 in 2,000,000 and 3 in 6,400
logic [20:0] scan_acc;
logic [12:0] bit_acc;
logic [23:0] state, cur;
logic [4:0]  k;                          // the key being compared; 24 idle
logic [7:0]  buf_q [16];
logic [3:0]  head, tail;
logic [3:0]  tbit;                       // bits left; 0 idle
logic [9:0]  tsr;
logic        kick;                       // the scan's tra_complete, a clock after it has queued its bytes

always_ff @(posedge clk) begin
    logic scan, tick, done, start;
    logic [3:0] h;
    logic [7:0] note;
    scan = !hold && scan_acc >= 21'd1_999_997;
    if (!hold) scan_acc <= scan ? scan_acc - 21'd1_999_997 : scan_acc + 21'd3;
    tick = !hold && bit_acc >= 13'd6_397;
    if (!hold) bit_acc <= tick ? bit_acc - 13'd6_397 : bit_acc + 13'd3;

    kick <= 1'b0;
    h = head;
    if (scan) begin
        cur <= keys;
        if (keys == state) begin h = h + 4'd1; buf_q[h] <= 8'hFE; kick <= 1'b1; end
        else k <= 5'd0;
    end else if (k != 5'd24) begin
        note = 8'h3C + {3'b000, k};
        if (state[k] != cur[k]) begin
            buf_q[h + 4'd1] <= cur[k] ? 8'h90 : 8'h80;
            buf_q[h + 4'd2] <= note;
            buf_q[h + 4'd3] <= 8'h7F;
            h = h + 4'd3;
        end
        k <= k + 5'd1;
        if (k == 5'd23) begin state <= cur; kick <= 1'b1; end
    end
    head <= h;

    // the transmitter: a frame is 10 bit times; tra_complete at its end, or from a scan when idle
    done = 1'b0;
    if (tick && tbit != 4'd0) begin
        txd <= tsr[0];
        tsr <= {1'b1, tsr[9:1]};
        tbit <= tbit - 4'd1;
        done = tbit == 4'd1;
    end
    start = done || (kick && tbit == 4'd0);
    if (start && head != tail) begin
        tsr <= {1'b1, buf_q[tail], 1'b0};
        tbit <= 4'd10;
        tail <= tail + 4'd1;
    end

    if (reset) begin
        scan_acc <= 21'd0; bit_acc <= 13'd0; state <= 24'd0; cur <= 24'd0; k <= 5'd24;
        head <= 4'd0; tail <= 4'd0; tbit <= 4'd0; tsr <= 10'h3FF; txd <= 1'b1; kick <= 1'b0;
        for (int i = 0; i < 16; i++) buf_q[i] <= 8'h00;
    end
`ifdef VERILATOR  // st_lists: write
    if (st_we) case (st_a)
    6'h0: scan_acc <= ($bits(scan_acc))'(st_wd);
    6'h1: bit_acc <= ($bits(bit_acc))'(st_wd);
    6'h2: kick <= ($bits(kick))'(st_wd);
    6'h3: cur <= ($bits(cur))'(st_wd);
    6'h4: buf_q[0] <= ($bits(buf_q[0]))'(st_wd);
    6'h5: buf_q[1] <= ($bits(buf_q[1]))'(st_wd);
    6'h6: buf_q[2] <= ($bits(buf_q[2]))'(st_wd);
    6'h7: buf_q[3] <= ($bits(buf_q[3]))'(st_wd);
    6'h8: buf_q[4] <= ($bits(buf_q[4]))'(st_wd);
    6'h9: buf_q[5] <= ($bits(buf_q[5]))'(st_wd);
    6'hA: buf_q[6] <= ($bits(buf_q[6]))'(st_wd);
    6'hB: buf_q[7] <= ($bits(buf_q[7]))'(st_wd);
    6'hC: buf_q[8] <= ($bits(buf_q[8]))'(st_wd);
    6'hD: buf_q[9] <= ($bits(buf_q[9]))'(st_wd);
    6'hE: buf_q[10] <= ($bits(buf_q[10]))'(st_wd);
    6'hF: buf_q[11] <= ($bits(buf_q[11]))'(st_wd);
    6'h10: buf_q[12] <= ($bits(buf_q[12]))'(st_wd);
    6'h11: buf_q[13] <= ($bits(buf_q[13]))'(st_wd);
    6'h12: buf_q[14] <= ($bits(buf_q[14]))'(st_wd);
    6'h13: buf_q[15] <= ($bits(buf_q[15]))'(st_wd);
    6'h14: k <= ($bits(k))'(st_wd);
    6'h15: state <= ($bits(state))'(st_wd);
    6'h16: txd <= ($bits(txd))'(st_wd);
    6'h17: tsr <= ($bits(tsr))'(st_wd);
    6'h18: tbit <= ($bits(tbit))'(st_wd);
    6'h19: tail <= ($bits(tail))'(st_wd);
    6'h1A: head <= ($bits(head))'(st_wd);
    default: ;
    endcase
`endif  // st_lists: write
end

// st_lists: begin
// [Firebeat] The state dump's register block (docs/STATE.md), generated by scripts/st_lists.py:
// a word a register, in the order of its always_ff block; written in Verilator only.
always_comb begin
    st_d = 32'd0;
    case (st_a)
    6'h0: st_d = 32'(scan_acc);
    6'h1: st_d = 32'(bit_acc);
    6'h2: st_d = 32'(kick);
    6'h3: st_d = 32'(cur);
    6'h4: st_d = 32'(buf_q[0]);
    6'h5: st_d = 32'(buf_q[1]);
    6'h6: st_d = 32'(buf_q[2]);
    6'h7: st_d = 32'(buf_q[3]);
    6'h8: st_d = 32'(buf_q[4]);
    6'h9: st_d = 32'(buf_q[5]);
    6'hA: st_d = 32'(buf_q[6]);
    6'hB: st_d = 32'(buf_q[7]);
    6'hC: st_d = 32'(buf_q[8]);
    6'hD: st_d = 32'(buf_q[9]);
    6'hE: st_d = 32'(buf_q[10]);
    6'hF: st_d = 32'(buf_q[11]);
    6'h10: st_d = 32'(buf_q[12]);
    6'h11: st_d = 32'(buf_q[13]);
    6'h12: st_d = 32'(buf_q[14]);
    6'h13: st_d = 32'(buf_q[15]);
    6'h14: st_d = 32'(k);
    6'h15: st_d = 32'(state);
    6'h16: st_d = 32'(txd);
    6'h17: st_d = 32'(tsr);
    6'h18: st_d = 32'(tbit);
    6'h19: st_d = 32'(tail);
    6'h1A: st_d = 32'(head);
    default: ;
    endcase
end
// st_lists: end

endmodule
