"""Write rtl/board/fb_kbm_en.svh: the root-directory words that point Keyboardmania's six
instruction screens at the disc's unused English copies (X*.ZCC), for fb_kbm_en.

    python scripts/gen_kbm_en.py <disc.bin> [<disc.bin> ...]

Each .bin is a data disc extracted with chdman extractcd (MODE1/2352, track 1 at frame 0): kbm's
gq974-ja c01, kbh's gu974-ka a01. For each pair, the plain file's directory record gets the X
file's extent and size, both byte orders. A table entry is {the volume's size in blocks (the primary
volume descriptor's bytes 80-83, which tells the discs apart), frame, word, word on the disc,
patched word}; fb_kbm_en replaces only a word that still reads as the disc's.
"""
import struct
import sys
from pathlib import Path

PAIRS = [("DEMO", "XDEMO"), ("ENTRY_L", "XENTRY_L"), ("MAIN_L", "XMAIN_L"), ("MAIN_R", "XMAIN_R"),
         ("MU_SEL", "XMU_SEL"), ("MU_SEL_R", "XMU_SELR")]
RAW = 2352


def sector(f, n):
    f.seek(n * RAW + 16)
    return f.read(2048)


def root_records(f):
    pvd = sector(f, 16)
    assert pvd[1:6] == b"CD001", "no ISO 9660 volume"
    vol = struct.unpack_from("<I", pvd, 80)[0]
    lba, size = struct.unpack_from("<I", pvd, 156 + 2)[0], struct.unpack_from("<I", pvd, 156 + 10)[0]
    recs = {}
    for s in range((size + 2047) // 2048):
        d = sector(f, lba + s)
        i = 0
        while i < 2048 and d[i]:
            n = d[i + 32]
            name = d[i + 33:i + 33 + n].decode("latin1").split(";")[0]
            if name.endswith(".ZCC"):
                recs[name[:-4]] = (lba + s, i, d[i + 2:i + 18])
            i += d[i]
    return vol, recs


def main():
    rows = []
    for p in sys.argv[1:]:
        with open(p, "rb") as f:
            vol, recs = root_records(f)
        for a, b in PAIRS:
            frame, off, old = recs[a]
            new = recs[b][2]
            for k in range(0, 16, 2):
                ow, nw = struct.unpack_from("<H", old, k)[0], struct.unpack_from("<H", new, k)[0]
                if ow != nw:
                    rows.append((vol, frame, (off + 2 + k) // 2, ow, nw, f"{Path(p).name} {a}"))
    out = Path(__file__).resolve().parent.parent / "rtl/board/fb_kbm_en.svh"
    lines = ["// Generated by scripts/gen_kbm_en.py; do not edit.",
             "// {volume blocks, frame, word in the frame's 2,048 bytes, the disc's word, the English file's}",
             f"localparam int KBM_EN_N = {len(rows)};",
             f"localparam logic [97:0] KBM_EN [KBM_EN_N] = '{{"]
    for i, (v, fr, w, o, n, why) in enumerate(rows):
        sep = "," if i < len(rows) - 1 else ""
        lines.append(f"    {{32'd{v}, 24'd{fr}, 10'd{w}, 16'h{o:04X}, 16'h{n:04X}}}{sep}  // {why}")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} words -> {out}")


if __name__ == "__main__":
    main()
