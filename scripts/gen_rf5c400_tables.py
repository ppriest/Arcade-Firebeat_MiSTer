"""rtl/spu/fb_rf5c400_tables.svh: the RF5C400's tables as MAME computes them (rf5c400.cpp
init_static_tables, envelope_tables::init for a 16.9344 MHz clock), in fixed point:

    vol_t(i)   volume_table, the integers MAME keeps
    pan_t(i)   pan_table, Q1.24
    ar_t(i), dr_t(i), rr_t(i)   the envelope steps a sample, Q2.30 (signed 32 bits)

    python scripts/gen_rf5c400_tables.py
"""
import math
from pathlib import Path

CLOCK = 16934400
OUT = Path(__file__).resolve().parent.parent / "rtl" / "spu" / "fb_rf5c400_tables.svh"


def tables():
    vol, mx = [], 255.0
    for _ in range(256):
        vol.append(int(mx) & 0xFFFF)
        mx /= math.pow(10.0, (4.5 / (256.0 / 16.0)) / 20)
    pan = [math.sqrt(0x47 - i) / math.sqrt(0x47) if i < 0x48 else 0.0 for i in range(256)]

    rate = CLOCK // 384

    def env(speed, lo, hi, sign, below):
        r = sign / (speed * rate)
        t = []
        for i in range(0x9F):
            if i < lo:
                t.append(below if below is not None else r)
            elif i < hi:
                t.append(r * (hi - i) / (hi - lo))
            else:
                t.append(0.0)
        return t
    ar = env(0.1, 0x02, 0x80, 1.0, 1.0)
    dr = env(2.0, 0x20, 0x73, -5.0, None)
    rr = env(0.7, 0x20, 0x54, -5.0, None)
    return vol, pan, ar, dr, rr


def q(x, frac):
    return int(round(x * (1 << frac)))


def main():
    vol, pan, ar, dr, rr = tables()
    lines = ["// Generated by scripts/gen_rf5c400_tables.py from MAME's rf5c400.cpp; do not edit.", ""]

    def func(name, width, vals, signed=False):
        ty = f"logic {'signed ' if signed else ''}[{width - 1}:0]"
        lines.append(f"function automatic {ty} {name}(input logic [7:0] i);")
        lines.append("    case (i)")
        for i, v in enumerate(vals):
            if v:
                lines.append(f"    8'd{i}: return {'-' if v < 0 else ''}{width}'sd{abs(v)};" if signed
                             else f"    8'd{i}: return {width}'d{v};")
        lines.append("    default: return '0;")
        lines.append("    endcase")
        lines.append("endfunction")
        lines.append("")
    func("vol_t", 8, vol)
    func("pan_t", 25, [q(p, 24) for p in pan])
    func("ar_t", 32, [q(v, 30) for v in ar], True)
    func("dr_t", 32, [q(v, 30) for v in dr], True)
    func("rr_t", 32, [q(v, 30) for v in rr], True)
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: vol {vol[0]}..{vol[255]}, ar[2] {q(ar[2], 30)}, dr[0] {q(dr[0], 30)}")


if __name__ == "__main__":
    main()
